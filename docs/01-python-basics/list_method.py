#1.append()     在列表的尾部加元素                                    s.append()
#2.insert()      在指定索引插入元素                                   s.insert(索引,元素)
#3.remove()     移除列表第一个匹配到的值                               s.remove(指定值)
#4.pop()        删除列表中指定索引位置的元素（若未指定索引默认删最后一个）    s.pop(索引)
#5.sort()         对列表进行排列（列表数据类型一致才可以排列）             s.sort()

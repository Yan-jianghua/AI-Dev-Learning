#列表名 = [元素1,元素2,.....]可以有重复的元素，可修改，有序，可以存储不同类型元素
#顺序从零开始,倒序从-1开始   a[2]表示a列表中第3个元素
s=[1,2,3,"hello",True]
#获取
print(s)
print(s[1])
print(s[0])
print(s[-1])
#修改    若指定索引超过范围会报错
s[0]=10
s[1]="love"
print(s[1])
#删除    删除元素后其他元素索引前移
del s[-2]
print(s)
print(s[1])
#遍历
for i in s:
    print(i)
#切片    序列数据[开始索引:结束索引:步长]    1.分为正向索引和反向索引  2.索引包括开始索引不包括结束索引
s1 = ["a","b","c","d",2,3,4]
l = s1[0:2]
print(l)
l1 = s1[-2:-1]
print(l1)